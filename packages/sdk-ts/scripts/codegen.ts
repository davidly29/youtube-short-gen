/**
 * Generate the TypeScript and Python SDKs from docs/api/openapi.yaml (E12-02).
 * Pure functions: `pnpm -F sdk-ts generate` writes the files, and the tests check they're current.
 */

export interface JsonSchema {
  $ref?: string;
  type?: string;
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  additionalProperties?: boolean | JsonSchema;
  description?: string;
  default?: unknown;
  format?: string;
  minimum?: number;
  maximum?: number;
}

interface Parameter {
  name: string;
  in: "path" | "query" | "header";
  required?: boolean;
  description?: string;
  schema: JsonSchema;
}

interface Operation {
  operationId: string;
  summary?: string;
  description?: string;
  tags?: string[];
  parameters?: Parameter[];
  requestBody?: { content: { "application/json": { schema: JsonSchema } } };
  responses: Record<string, { content?: { "application/json"?: { schema: JsonSchema } } }>;
}

export interface OpenApiDoc {
  info: { title: string; version: string };
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, JsonSchema> };
}

/** One API operation, flattened for both generators. */
export interface Op {
  id: string;
  method: string;
  path: string;
  summary: string;
  description: string;
  pathParams: Parameter[];
  queryParams: Parameter[];
  body?: string;
  bodySchema?: JsonSchema;
  status: number;
  response: string;
}

const refName = (ref: string) => ref.replace("#/components/schemas/", "");
const pascal = (s: string) =>
  s
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
const camel = (s: string) => {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};
export const snake = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

export function operations(doc: OpenApiDoc): Op[] {
  const ops: Op[] = [];
  for (const [path, methods] of Object.entries(doc.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      const success = Object.keys(op.responses).find((s) => s.startsWith("2"));
      const schema = success ? op.responses[success]?.content?.["application/json"]?.schema : undefined;
      if (!success || !schema?.$ref) throw new Error(`${op.operationId}: no JSON success response`);
      const body = op.requestBody?.content["application/json"].schema;
      if (body && !body.$ref) throw new Error(`${op.operationId}: request body must be a $ref`);
      ops.push({
        id: op.operationId,
        method: method.toUpperCase(),
        path,
        summary: op.summary ?? op.operationId,
        description: (op.description ?? "").trim(),
        pathParams: (op.parameters ?? []).filter((p) => p.in === "path"),
        queryParams: (op.parameters ?? []).filter((p) => p.in === "query"),
        body: body?.$ref ? refName(body.$ref) : undefined,
        bodySchema: body?.$ref ? doc.components.schemas[refName(body.$ref)] : undefined,
        status: Number(success),
        response: refName(schema.$ref),
      });
    }
  }
  return ops;
}

// ---------------------------------------------------------------- TypeScript

function tsType(s: JsonSchema): string {
  if (s.$ref) return refName(s.$ref);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  const union = s.anyOf ?? s.oneOf;
  if (union) return union.map(tsType).join(" | ");
  switch (s.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${wrap(tsType(s.items ?? {}))}[]`;
    case "object":
      return tsObject(s);
    default:
      return "unknown";
  }
}

const wrap = (t: string) => (t.includes("|") ? `(${t})` : t);

const jsdoc = (text: string | undefined, indent = "") =>
  text ? `${indent}/** ${text.replace(/\*\//g, "*\\/").replace(/\n+/g, " ")} */\n` : "";

function tsObject(s: JsonSchema): string {
  const req = new Set(s.required ?? []);
  const lines = Object.entries(s.properties ?? {}).map(
    ([k, v]) => `${jsdoc(v.description)}${k}${req.has(k) ? "" : "?"}: ${tsType(v)};`,
  );
  if (s.additionalProperties && s.additionalProperties !== true && !s.properties) {
    return `Record<string, unknown>`;
  }
  if (s.additionalProperties !== false && s.additionalProperties !== undefined)
    lines.push("[key: string]: unknown;");
  return `{ ${lines.join("\n")} }`;
}

export function renderTs(doc: OpenApiDoc, spec: string): string {
  const ops = operations(doc);
  const out: string[] = [
    `// GENERATED by \`pnpm -F sdk-ts generate\` from docs/api/openapi.yaml. Do not edit by hand.`,
    ``,
    `export const API_VERSION = ${JSON.stringify(doc.info.version)};`,
    `/** SHA-256 of the OpenAPI document this SDK was generated from. */`,
    `export const SPEC_SHA256 = ${JSON.stringify(spec)};`,
    ``,
  ];
  for (const [name, schema] of Object.entries(doc.components.schemas)) {
    out.push(`${jsdoc(schema.description)}export type ${name} = ${tsType(schema)};`, ``);
  }
  out.push(
    `export type HttpMethod = "GET" | "POST" | "DELETE";`,
    `export interface RequestSpec { operationId: string; method: HttpMethod; path: string; query?: Record<string, string | number | boolean | undefined>; body?: unknown }`,
    ``,
    `/** Every operation of the ShortLoop API. \`request\` does the HTTP call. */`,
    `export abstract class GeneratedClient {`,
    `  protected abstract request<T>(spec: RequestSpec): Promise<T>;`,
  );
  for (const op of ops) {
    const args: string[] = op.pathParams.map((p) => `${camel(p.name)}: string`);
    if (op.body) {
      const required = (op.bodySchema?.required ?? []).length > 0;
      args.push(`body${required ? "" : "?"}: ${op.body}`);
    }
    if (op.queryParams.length) {
      const fields = op.queryParams.map((p) => `${jsdoc(p.description)}${p.name}?: ${tsType(p.schema)}`);
      args.push(`query: { ${fields.join("; ")} } = {}`);
    }
    let path = JSON.stringify(op.path);
    for (const p of op.pathParams) {
      path = path.replace(`{${p.name}}`, `\${encodeURIComponent(${camel(p.name)})}`);
    }
    path = path.includes("${") ? "`" + path.slice(1, -1) + "`" : path;
    const doc = [op.summary, op.description].filter(Boolean).join("\n\n").replace(/\*\//g, "*\\/");
    out.push(
      ``,
      `  /**\n${doc
        .split("\n")
        .map((l) => `   *${l ? " " + l : ""}`)
        .join("\n")}\n   */`,
      `  ${camel(op.id)}(${args.join(", ")}): Promise<${op.response}> {`,
      `    return this.request<${op.response}>({ operationId: ${JSON.stringify(op.id)}, method: ${JSON.stringify(op.method)}, path: ${path}${op.queryParams.length ? ", query" : ""}${op.body ? ", body" : ""} });`,
      `  }`,
    );
  }
  out.push(`}`, ``);
  return out.join("\n");
}

// ---------------------------------------------------------------- Python

const PY_KEYWORDS = new Set([
  "from",
  "class",
  "def",
  "global",
  "import",
  "lambda",
  "in",
  "is",
  "not",
  "pass",
]);
const pyName = (s: string) => (PY_KEYWORDS.has(s) ? `${s}_` : s);

function pyLiteral(v: unknown): string {
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "boolean") return v ? "True" : "False";
  if (v === null) return "None";
  return String(v);
}

class PyTypes {
  readonly classes: string[] = [];
  private readonly emitted = new Set<string>();
  constructor(private readonly schemas: Record<string, JsonSchema>) {}

  type(s: JsonSchema, hint: string): string {
    if (s.$ref) return refName(s.$ref);
    if (s.const !== undefined) return `Literal[${pyLiteral(s.const)}]`;
    if (s.enum) return `Literal[${s.enum.map(pyLiteral).join(", ")}]`;
    const union = s.anyOf ?? s.oneOf;
    if (union) {
      if (union.every((u) => u.const !== undefined)) {
        return `Literal[${union.map((u) => pyLiteral(u.const)).join(", ")}]`;
      }
      return `Union[${union.map((u, i) => this.type(u, `${hint}${i}`)).join(", ")}]`;
    }
    switch (s.type) {
      case "string":
        return "str";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "boolean":
        return "bool";
      case "array":
        return `List[${this.type(s.items ?? {}, `${hint}Item`)}]`;
      case "object":
        if (!s.properties) return "Dict[str, Any]";
        this.typedDict(hint, s);
        return hint;
      default:
        return "Any";
    }
  }

  typedDict(name: string, s: JsonSchema): void {
    if (this.emitted.has(name)) return;
    this.emitted.add(name);
    const req = new Set(s.required ?? []);
    const entries = Object.entries(s.properties ?? {});
    const field = ([k, v]: [string, JsonSchema]) =>
      `    ${k}: ${this.type(v, name + pascal(k))}${v.description ? `\n    """${v.description.replace(/"""/g, "'''")}"""` : ""}`;
    const required = entries.filter(([k]) => req.has(k)).map(field);
    const optional = entries.filter(([k]) => !req.has(k)).map(field);
    const doc = s.description ? `    """${s.description.replace(/"""/g, "'''")}"""\n` : "";
    if (optional.length && required.length) {
      this.classes.push(`class _${name}Required(TypedDict):\n${required.join("\n")}\n`);
      this.classes.push(`class ${name}(_${name}Required, total=False):\n${doc}${optional.join("\n")}\n`);
    } else if (optional.length) {
      this.classes.push(`class ${name}(TypedDict, total=False):\n${doc}${optional.join("\n")}\n`);
    } else {
      this.classes.push(`class ${name}(TypedDict):\n${doc}${required.join("\n") || "    pass"}\n`);
    }
  }

  alias(name: string, s: JsonSchema): void {
    if (s.type === "object" && s.properties) return this.typedDict(name, s);
    this.classes.push(`${name} = ${this.type(s, name)}\n`);
  }

  all(): void {
    for (const [name, schema] of Object.entries(this.schemas)) this.alias(name, schema);
  }
}

export function renderPy(doc: OpenApiDoc, spec: string): string {
  const types = new PyTypes(doc.components.schemas);
  types.all();
  const methods: string[] = [];
  for (const op of operations(doc)) {
    const params: string[] = ["self"];
    const kw: string[] = [];
    for (const p of op.pathParams) params.push(`${pyName(p.name)}: str`);
    const bodyLines: string[] = [];
    const queryLines: string[] = [];
    const bodyProps = Object.entries(op.bodySchema?.properties ?? {});
    const req = new Set(op.bodySchema?.required ?? []);
    for (const [k, v] of bodyProps.filter(([k]) => req.has(k))) {
      kw.push(`${pyName(k)}: ${types.type(v, `${op.body}${pascal(k)}`)}`);
      bodyLines.push(`        body[${JSON.stringify(k)}] = ${pyName(k)}`);
    }
    for (const [k, v] of bodyProps.filter(([k]) => !req.has(k))) {
      kw.push(`${pyName(k)}: Optional[${types.type(v, `${op.body}${pascal(k)}`)}] = None`);
      bodyLines.push(
        `        if ${pyName(k)} is not None:\n            body[${JSON.stringify(k)}] = ${pyName(k)}`,
      );
    }
    for (const q of op.queryParams) {
      kw.push(`${pyName(q.name)}: Optional[${types.type(q.schema, "Any")}] = None`);
      queryLines.push(
        `        if ${pyName(q.name)} is not None:\n            query[${JSON.stringify(q.name)}] = ${pyName(q.name)}`,
      );
    }
    if (kw.length) params.push("*", ...kw);
    let path = op.path;
    const fmt = op.pathParams.length > 0;
    for (const p of op.pathParams) path = path.replace(`{${p.name}}`, `{_q(${pyName(p.name)})}`);
    const docText = [op.summary, op.description].filter(Boolean).join("\n\n").replace(/"""/g, "'''");
    const lines = [
      `    def ${snake(op.id)}(${params.join(", ")}) -> ${op.response}:`,
      `        """${docText
        .split("\n")
        .map((l, i) => (i === 0 || !l ? l : `        ${l}`))
        .join("\n")}\n        """`,
    ];
    if (op.body) lines.push(`        body: Dict[str, Any] = {}`, ...bodyLines);
    if (op.queryParams.length) lines.push(`        query: Dict[str, Any] = {}`, ...queryLines);
    lines.push(
      `        return self._request(${JSON.stringify(op.id)}, ${JSON.stringify(op.method)}, ${fmt ? "f" : ""}${JSON.stringify(path)}${op.queryParams.length ? ", query=query" : ""}${op.body ? ", body=body" : ""})  # type: ignore[return-value]`,
    );
    methods.push(lines.join("\n"));
  }
  return [
    `# GENERATED by \`pnpm -F sdk-ts generate\` from docs/api/openapi.yaml. Do not edit by hand.`,
    `# fmt: off`,
    `from __future__ import annotations`,
    ``,
    `from typing import Any, Dict, List, Literal, Optional, TypedDict, Union`,
    `from urllib.parse import quote`,
    ``,
    `API_VERSION = ${JSON.stringify(doc.info.version)}`,
    `SPEC_SHA256 = ${JSON.stringify(spec)}`,
    ``,
    ``,
    `def _q(value: str) -> str:`,
    `    return quote(value, safe="")`,
    ``,
    ``,
    ...types.classes.map((c) => c + "\n"),
    `class GeneratedClient:`,
    `    """Every operation of the ShortLoop API. Subclasses implement \`_request\`."""`,
    ``,
    `    def _request(self, operation_id: str, method: str, path: str, *, query: Optional[Dict[str, Any]] = None, body: Optional[Dict[str, Any]] = None) -> Any:`,
    `        raise NotImplementedError`,
    ``,
    methods.join("\n\n"),
    ``,
  ].join("\n");
}
