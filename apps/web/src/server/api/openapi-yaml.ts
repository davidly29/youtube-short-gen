import { stringify } from "yaml";
import { buildOpenApi } from "./spec";

const HEADER = `# GENERATED by \`pnpm -F web openapi\` from apps/web/src/server/api/spec.ts. Do not edit by hand.
# Public REST API (E12-01). Served live at /api/v1/openapi.json.
`;

/** docs/api/openapi.yaml, exactly as committed. */
export function renderOpenApiYaml(): string {
  return HEADER + stringify(buildOpenApi(), { lineWidth: 0, aliasDuplicateObjects: false });
}
